import hashlib
import json
import os
import secrets
import subprocess
from datetime import datetime, timezone
from pathlib import Path

KIND = os.environ.get("SOUNDSCAPE", "").strip().lower()
ROOT = Path(os.environ.get("SOURCE_AUDIO_DIR", "generated-audio"))
DURATION_SECONDS = 3600
SAMPLE_RATE = 48000
AMPLITUDE = 0.12
NOISE_COLORS = {
    "white_noise": "white",
    "brown_noise": "brown",
}


def probe_seconds(path: Path) -> float:
    result = subprocess.run(
        [
            "ffprobe", "-v", "error",
            "-show_entries", "format=duration",
            "-of", "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=True,
        timeout=30,
    )
    return float(result.stdout.strip())


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> None:
    if KIND not in NOISE_COLORS:
        raise RuntimeError(
            f"Retired or unsupported sound category {KIND!r}; "
            "TV OFF permits only locally generated White Noise, Brown Noise and Original Music."
        )

    ROOT.mkdir(parents=True, exist_ok=True)
    seed = secrets.randbelow(2**32 - 1) + 1
    color = NOISE_COLORS[KIND]
    target = ROOT / f"{KIND}_original_{seed}.mp3"

    print(
        f"GENERATE ORIGINAL SYNTHETIC AUDIO: {KIND} | "
        f"FFmpeg anoisesrc color={color} | {DURATION_SECONDS}s | seed={seed}",
        flush=True,
    )
    subprocess.run(
        [
            "ffmpeg", "-y", "-hide_banner",
            "-f", "lavfi", "-i",
            (
                f"anoisesrc=color={color}:amplitude={AMPLITUDE}:"
                f"sample_rate={SAMPLE_RATE}:duration={DURATION_SECONDS}:seed={seed}"
            ),
            "-ac", "2",
            "-c:a", "libmp3lame",
            "-b:a", "192k",
            str(target),
        ],
        check=True,
        timeout=480,
    )

    actual_duration = probe_seconds(target)
    if actual_duration < DURATION_SECONDS - 1:
        target.unlink(missing_ok=True)
        raise RuntimeError(
            f"Synthetic {KIND} audio is too short: {actual_duration:.2f}s"
        )

    audio_sha256 = sha256(target)
    sidecar_path = ROOT / "manifest.sha256"
    sidecar_path.write_text(f"{audio_sha256}  {target.name}\n", encoding="utf-8")

    manifest_entry = {
        "file": target.name,
        "creator": "TV OFF (original synthetic audio)",
        "source_url": "Original audio generated locally by TV OFF; no external recording.",
        "license": (
            "Original synthetic audio generated by TV OFF with FFmpeg; "
            "no third-party recording, sample or borrowed audio used (CC0 not applicable)."
        ),
        "title": f"Original {KIND.replace('_', ' ').title()}",
        "platform": "TV OFF / FFmpeg",
        "audio_type": "synthetic",
        "noise_color": color,
        "random_seed": seed,
        "duration_seconds": round(actual_duration, 2),
        "sha256": audio_sha256,
        "downloaded_at": datetime.now(timezone.utc).isoformat(),
    }

    manifest_path = ROOT / "manifest.json"
    manifest_path.write_text(
        json.dumps({KIND: manifest_entry}, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print(
        f"SYNTHETIC AUDIO PREFLIGHT PASSED: {KIND} | "
        f"{actual_duration:.2f}s | seed={seed} | sha256={audio_sha256} | manifest.sha256 written | "
        "local-only; no external audio source",
        flush=True,
    )


if __name__ == "__main__":
    main()
